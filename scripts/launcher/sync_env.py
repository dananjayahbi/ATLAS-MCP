"""Generate `frontend/.env.local` from the root `.env`.

Next.js only reads env files inside its own project root, so the API proxy
needs a second copy of the two server-side values. Only non-`NEXT_PUBLIC_`
keys are copied, so nothing here can reach the browser bundle
(Doc 01 §14.2).

Usage:  python scripts/launcher/sync_env.py
"""

from __future__ import annotations

import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

REPO = Path(__file__).resolve().parents[2]
ROOT_ENV = REPO / ".env"
FRONTEND_ENV = REPO / "frontend" / ".env.local"

#: Keys the proxy / server components need. Everything else stays backend-only.
FORWARDED = ("ATLAS_BACKEND_URL", "ATLAS_API_TOKEN", "ATLAS_WEB_ORIGIN")


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip().strip("'\"")
    return values


def main() -> int:
    values = read_env(ROOT_ENV)
    if not values:
        sys.stderr.write(f"[X] {ROOT_ENV} is missing or empty.\n")
        sys.stderr.write("    Run: .venv\\Scripts\\python.exe scripts\\bootstrap_dev.py\n")
        return 1

    missing = [key for key in ("ATLAS_BACKEND_URL", "ATLAS_API_TOKEN") if not values.get(key)]
    if missing:
        sys.stderr.write(f"[X] {ROOT_ENV} lacks: {', '.join(missing)}\n")
        return 1

    lines = ["# Generated by scripts/launcher/sync_env.py — do not commit."]
    for key in FORWARDED:
        value = values.get(key)
        if value:
            lines.append(f"{key}={value}")
    lines.append("")

    FRONTEND_ENV.parent.mkdir(parents=True, exist_ok=True)
    FRONTEND_ENV.write_text("\n".join(lines), encoding="utf-8")
    print(f"[i] wrote {FRONTEND_ENV}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
