"""Thumbnail generation for stored images.

The board, the list view and the markup rail only ever need a card-sized
representation of an image. Serving the original screenshot for a 44 px tile
means a dashboard with dozens of attached screenshots downloads hundreds of
megabytes, so every image asset gets a downscaled sibling written at ingest
time and the UI reads that instead.

Thumbnails are best-effort: a format Pillow cannot decode (or a Pillow that is
not installed) must never fail the upload. The caller falls back to the
original bytes when `generate_thumbnail` returns `None`.
"""

from __future__ import annotations

import io
import logging
from dataclasses import dataclass
from pathlib import Path

logger = logging.getLogger("atlas.thumbnails")

#: Longest edge of a generated thumbnail, in pixels. Comfortably above the
#: largest on-screen use (~176 px in the markup rail) so it stays crisp on a
#: 2x display without paying for full resolution.
THUMBNAIL_MAX_EDGE = 400

#: JPEG quality for opaque thumbnails. Screenshots are mostly flat UI, so 82 is
#: visually lossless at this size and a fraction of the PNG size.
JPEG_QUALITY = 82

THUMBNAIL_PREFIX = "thumb_"


@dataclass(frozen=True)
class Thumbnail:
    """Generated bytes plus everything needed to store them as a sibling file."""

    data: bytes
    suffix: str
    mime_type: str


def _load(path: Path):
    from PIL import Image

    image = Image.open(path)
    # A multi-frame source (animated WebP/GIF) would otherwise thumbnail frame 1
    # of an unrelated animation; `seek(0)` pins it explicitly.
    try:
        image.seek(0)
    except (EOFError, AttributeError):  # pragma: no cover - single-frame images
        pass
    return image


def _flatten(image):
    """Drop alpha by compositing onto white, which is what a screenshot assumes."""
    from PIL import Image

    if image.mode in ("RGBA", "LA") or (image.mode == "P" and "transparency" in image.info):
        converted = image.convert("RGBA")
        canvas = Image.new("RGB", converted.size, (255, 255, 255))
        canvas.paste(converted, mask=converted.split()[-1])
        return canvas
    return image.convert("RGB")


def generate_thumbnail_bytes(source: bytes | str | Path, *, max_edge: int = THUMBNAIL_MAX_EDGE) -> Thumbnail | None:
    """Downscale `source` to fit `max_edge`; `None` when it is not decodable.

    `source` may be raw bytes or a path (as `str` or `Path`), because callers
    hold either a `StoredFile.absolute_path` string or bytes already in memory.
    Transparent sources stay PNG so the alpha survives; everything else becomes
    JPEG, which is far smaller for screenshots.
    """
    try:
        from PIL import Image
    except ImportError:  # pragma: no cover - Pillow is a declared dependency
        logger.warning("Pillow is unavailable; skipping thumbnail generation")
        return None

    try:
        if isinstance(source, bytes):
            image = Image.open(io.BytesIO(source))
        else:
            image = _load(Path(source))
        image.seek(0)
    except Exception as exc:  # noqa: BLE001 - an undecodable image must not fail upload
        logger.info("thumbnail skipped: %s", exc)
        return None

    try:
        has_alpha = image.mode in ("RGBA", "LA") or (
            image.mode == "P" and "transparency" in image.info
        )
        image.thumbnail((max_edge, max_edge), Image.Resampling.LANCZOS)

        buffer = io.BytesIO()
        if has_alpha:
            image.save(buffer, format="PNG", optimize=True)
            return Thumbnail(data=buffer.getvalue(), suffix=".png", mime_type="image/png")

        _flatten(image).save(buffer, format="JPEG", quality=JPEG_QUALITY, optimize=True)
        return Thumbnail(data=buffer.getvalue(), suffix=".jpg", mime_type="image/jpeg")
    except Exception as exc:  # noqa: BLE001 - see module docstring
        logger.info("thumbnail encode skipped: %s", exc)
        return None
    finally:
        try:
            image.close()
        except Exception:  # pragma: no cover - defensive
            pass


def thumbnail_filename(original: str, suffix: str) -> str:
    """`shot.png` → `thumb_shot.jpg`; the stem keeps the pairing readable."""
    stem = Path(original).stem or "image"
    return f"{THUMBNAIL_PREFIX}{stem}{suffix}"
