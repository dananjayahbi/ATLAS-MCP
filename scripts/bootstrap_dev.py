"""Generate `.env`, bootstrap the SQLite DB, and print MCP client snippets.

Doc 01 §13: `scripts/bootstrap_dev.py` is the single entry point a new
developer runs after `git clone`.

Usage:
    python scripts/bootstrap_dev.py [--reset]
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import subprocess
import sys
from pathlib import Path

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

REPO = Path(__file__).resolve().parents[1]
VENV_PY = REPO / ".venv" / "Scripts" / "python.exe"
if not VENV_PY.exists():  # POSIX
    VENV_PY = REPO / ".venv" / "bin" / "python"
PY = str(VENV_PY if VENV_PY.exists() else sys.executable)

ENV_PATH = REPO / ".env"
FRONTEND_ENV_PATH = REPO / "frontend" / ".env.local"


def write_env(token: str) -> None:
    if ENV_PATH.exists():
        print(f"· .env already exists, leaving it alone ({ENV_PATH})")
    else:
        lines = [
            "# Generated by scripts/bootstrap_dev.py — do not commit.",
            "ATLAS_ENV=dev",
            "ATLAS_DEBUG=1",
            f"ATLAS_API_TOKEN={token}",
            f"ATLAS_STORAGE_ROOT={(REPO / 'storage').as_posix()}",
            f"ATLAS_DB_PATH={(REPO / 'backend' / 'data' / 'atlas.db').as_posix()}",
            "ATLAS_BACKEND_URL=http://127.0.0.1:8471",
            "ATLAS_WEB_ORIGIN=http://localhost:3471",
            "ATLAS_AGENT_ID=Agent-Claude",
            "ATLAS_PROJECT_SLUG=alpha",
            "ATLAS_LOG_LEVEL=INFO",
        ]
        ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"✓ wrote {ENV_PATH}")

    # Next.js only reads env files inside its own project root, so the proxy
    # needs a second copy. These values are server-side only (never
    # NEXT_PUBLIC_*), so the token still cannot reach the browser.
    fe_lines = [
        "# Generated by scripts/bootstrap_dev.py — do not commit.",
        f"ATLAS_BACKEND_URL=http://127.0.0.1:8471",
        f"ATLAS_API_TOKEN={token}",
        "ATLAS_WEB_ORIGIN=http://localhost:3471",
    ]
    existing = FRONTEND_ENV_PATH.read_text(encoding="utf-8") if FRONTEND_ENV_PATH.exists() else ""
    if f"ATLAS_API_TOKEN={token}" not in existing:
        FRONTEND_ENV_PATH.write_text("\n".join(fe_lines) + "\n", encoding="utf-8")
        print(f"✓ wrote {FRONTEND_ENV_PATH}")
    else:
        print(f"· {FRONTEND_ENV_PATH} is current")


def read_token() -> str:
    if not ENV_PATH.exists():
        return ""
    for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        if line.startswith("ATLAS_API_TOKEN="):
            return line.split("=", 1)[1].strip()
    return ""


def run(args: list[str]) -> None:
    env = {**os.environ, "ATLAS_SKIP_RECOVERY": "1"}
    print(f"$ {' '.join(args)}")
    subprocess.run(args, cwd=REPO / "backend", env=env, check=True)


def run_script(relative: str) -> None:
    """Run a repo script in-process-safe mode; a failure is reported, not fatal."""
    script = REPO / "scripts" / relative
    if not script.is_file():
        print(f"· skipped {relative} (not found)")
        return
    print(f"$ {PY} scripts/{relative}")
    result = subprocess.run([PY, str(script)], cwd=REPO)
    if result.returncode != 0:
        print(f"· {relative} exited {result.returncode} (see output above)")


def mcp_snippet(token: str) -> str:
    server = {
        "command": PY,
        "args": ["-m", "mcp_server"],
        "cwd": str(REPO),
        "env": {
            "ATLAS_BACKEND_URL": "http://127.0.0.1:8471",
            "ATLAS_API_TOKEN": token,
            "ATLAS_AGENT_ID": "Agent-Claude",
            "ATLAS_PROJECT_SLUG": "alpha",
            "ATLAS_STORAGE_ROOT": str(REPO / "storage"),
        },
    }
    vs_code = {"servers": {"atlas": server}}
    claude = {"mcpServers": {"atlas": server}}
    return (
        "── VS Code (.vscode/mcp.json) ──\n"
        + json.dumps(vs_code, indent=2)
        + "\n\n── Claude Desktop (claude_desktop_config.json) ──\n"
        + json.dumps(claude, indent=2)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reset", action="store_true", help="delete the SQLite DB first")
    args = parser.parse_args()

    token = read_token() or secrets.token_urlsafe(32)
    write_env(token)

    if args.reset:
        for suffix in ("", "-wal", "-shm"):
            candidate = REPO / "backend" / "data" / f"atlas.db{suffix}"
            candidate.unlink(missing_ok=True)
        print("✓ removed existing database")

    (REPO / "storage" / "projects").mkdir(parents=True, exist_ok=True)
    (REPO / "backend" / "data").mkdir(parents=True, exist_ok=True)

    run([PY, "manage.py", "migrate", "--noinput"])

    # VS Code MCP config + the Next.js copy of the server-side env.
    run_script("write_mcp_config.py")
    run_script("launcher/sync_env.py")

    print("\n✓ bootstrap complete\n")
    print(mcp_snippet(token))
    print(
        "\nNext:\n"
        "  start the stack : start-atlas.bat        (two CMD windows)\n"
        "  seed demo data  : .venv\\Scripts\\python.exe scripts\\seed_demo.py\n"
        "  verify the MCP  : .venv\\Scripts\\python.exe scripts\\mcp_probe.py\n"
        "\n  VS Code MCP is pre-configured in .vscode\\mcp.json\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
